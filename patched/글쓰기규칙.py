def _시트에서읽기(spreadsheet) -> dict[str, list[str]]:
    """`글쓰기규칙` 시트에서 규칙을 읽는다. 없으면 빈 것."""
    if spreadsheet is None:
        return {}
    try:
        장 = spreadsheet.worksheet(규칙시트이름)
    except Exception:
        return {}
    try:
        줄들 = 장.get_all_values()
    except Exception as 오류:
        logging.warning("글쓰기규칙 시트를 읽지 못했습니다: %s", 오류)
        return {}

    담긴것: dict[str, list[str]] = {}
    for 줄 in 줄들[1:]:          # 첫 줄은 머리글
        if len(줄) < 2:
            continue
        구분 = str(줄[0] or "").strip()
        내용 = str(줄[1] or "").rstrip()
        if not 구분:
            continue
        담긴것.setdefault(구분, []).append(내용)
    return {이름: 값 for 이름, 값 in 담긴것.items() if any(하나.strip() for 하나 in 값)}


def 규칙들(spreadsheet=None) -> dict[str, list[str]]:
    """시트가 있으면 시트, 없으면 사본."""
    사본 = {"구체성규칙": 구체성규칙, "제목규칙": 제목규칙, "공통규칙": 공통규칙}
    if os.getenv("USE_SHEET_WRITING_RULES", "1").strip().lower() in {"0", "false", "no", "off"}:
        return 사본
    시트것 = _시트에서읽기(spreadsheet)
    if not 시트것:
        return 사본
    쓴것 = dict(사본)
    for 이름 in 사본:
        if 시트것.get(이름):
            쓴것[이름] = 시트것[이름]
    logging.info("글쓰기 규칙을 시트에서 읽었습니다: %s",
                 ", ".join(f"{이름} {len(쓴것[이름])}줄" for 이름 in 쓴것))
    return 쓴것


def 요청문블록(spreadsheet=None) -> str:
    """API 요청문에 끼워 넣을 규칙 덩어리. 손으로 쓸 때와 같은 차례."""
    가진것 = 규칙들(spreadsheet)
